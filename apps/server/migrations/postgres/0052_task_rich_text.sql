-- Rich text and live co-editing for tasks (SQLite: ../0052_task_rich_text.sql).
ALTER TABLE tasks ADD COLUMN description_json TEXT;
ALTER TABLE task_comments ADD COLUMN body_json TEXT;
ALTER TABLE attachment_references ADD COLUMN inline BIGINT NOT NULL DEFAULT 0 CHECK (inline IN (0, 1));

CREATE TABLE task_collab_docs (
    task_id TEXT PRIMARY KEY REFERENCES tasks(id) ON DELETE CASCADE,
    workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    snapshot BYTEA NOT NULL,
    snapshot_seq BIGINT NOT NULL DEFAULT 0 CHECK (snapshot_seq >= 0),
    epoch TEXT NOT NULL CHECK (length(epoch) BETWEEN 1 AND 64),
    converter_version BIGINT NOT NULL,
    projected_seq BIGINT NOT NULL DEFAULT 0 CHECK (projected_seq >= 0),
    audited_at BIGINT,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);
CREATE INDEX task_collab_docs_workspace ON task_collab_docs (workspace_id);
CREATE TABLE task_collab_updates (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id TEXT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    data BYTEA NOT NULL,
    user_id TEXT REFERENCES users(id) ON DELETE SET NULL,
    created_at BIGINT NOT NULL
);
CREATE INDEX task_collab_updates_task ON task_collab_updates (task_id, seq);
CREATE INDEX task_collab_updates_workspace ON task_collab_updates (workspace_id);
CREATE INDEX task_collab_updates_user ON task_collab_updates (user_id);
CREATE FUNCTION task_collab_docs_scope_insert_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM tasks WHERE tasks.id = NEW.task_id AND tasks.workspace_id = NEW.workspace_id
    )
    THEN
        RAISE EXCEPTION 'collaborative document must belong to the task workspace';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER task_collab_docs_scope_insert
    BEFORE INSERT ON task_collab_docs
    FOR EACH ROW
    EXECUTE FUNCTION task_collab_docs_scope_insert_fn();
CREATE FUNCTION task_collab_docs_scope_immutable_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'collaborative document scope is immutable';
END;
$$;
CREATE TRIGGER task_collab_docs_scope_immutable
    BEFORE UPDATE OF workspace_id, task_id ON task_collab_docs
    FOR EACH ROW
    WHEN (NEW.workspace_id <> OLD.workspace_id OR NEW.task_id <> OLD.task_id)
    EXECUTE FUNCTION task_collab_docs_scope_immutable_fn();
CREATE FUNCTION task_collab_updates_scope_insert_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM tasks WHERE tasks.id = NEW.task_id AND tasks.workspace_id = NEW.workspace_id
    )
    THEN
        RAISE EXCEPTION 'collaborative update must belong to the task workspace';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER task_collab_updates_scope_insert
    BEFORE INSERT ON task_collab_updates
    FOR EACH ROW
    EXECUTE FUNCTION task_collab_updates_scope_insert_fn();
CREATE FUNCTION task_collab_updates_scope_immutable_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'collaborative update scope is immutable';
END;
$$;
CREATE TRIGGER task_collab_updates_scope_immutable
    BEFORE UPDATE OF workspace_id, task_id ON task_collab_updates
    FOR EACH ROW
    WHEN (NEW.workspace_id <> OLD.workspace_id OR NEW.task_id <> OLD.task_id)
    EXECUTE FUNCTION task_collab_updates_scope_immutable_fn();

-- A member mentioned in a task description is notified (kind `description_mentioned`). The
-- baseline's CHECKs are unnamed, so they are found by their text and replaced.
DO $$
DECLARE c record;
BEGIN
    FOR c IN
        SELECT conname FROM pg_constraint
        WHERE conrelid = 'notifications'::regclass AND contype = 'c'
          AND pg_get_constraintdef(oid) LIKE '%comment_mentioned%'
    LOOP
        EXECUTE format('ALTER TABLE notifications DROP CONSTRAINT %I', c.conname);
    END LOOP;
END;
$$;

ALTER TABLE notifications ADD CONSTRAINT notifications_kind_check
    CHECK (kind IN ('task_assigned', 'comment_mentioned', 'description_mentioned',
                    'page_comment_mentioned', 'page_mentioned', 'chat_mentioned'));
ALTER TABLE notifications ADD CONSTRAINT notifications_scope_check
    CHECK (
        (kind IN ('task_assigned', 'comment_mentioned', 'description_mentioned')
            AND task_id IS NOT NULL
            AND page_id IS NULL AND page_thread_id IS NULL AND page_comment_id IS NULL
            AND page_block_id IS NULL)
        OR (kind = 'page_comment_mentioned'
            AND task_id IS NULL AND comment_id IS NULL
            AND page_id IS NOT NULL AND page_thread_id IS NOT NULL AND page_comment_id IS NOT NULL
            AND page_block_id IS NULL)
        OR (kind = 'page_mentioned'
            AND task_id IS NULL AND comment_id IS NULL
            AND page_id IS NOT NULL AND page_thread_id IS NULL AND page_comment_id IS NULL)
        OR (kind = 'chat_mentioned'
            AND task_id IS NULL AND comment_id IS NULL
            AND page_id IS NULL AND page_thread_id IS NULL AND page_comment_id IS NULL
            AND page_block_id IS NULL)
    );
