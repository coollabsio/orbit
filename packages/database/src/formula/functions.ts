/** The formula functions (spec P3 15.6) with their signatures, for the editor's completion. */
export type FormulaFunction = { name: string; signature: string; group: string }

const GROUPS: Record<string, string[]> = {
  Logic: ['if(condition, then, else)', 'ifs(condition, value, …, else)', 'empty(value)', 'equal(a, b)', 'unequal(a, b)', 'let(name, value, result)', 'lets(name, value, …, result)'],
  Text: [
    'length(text)',
    'substring(text, start, end?)',
    'contains(text, search)',
    'lower(text)',
    'upper(text)',
    'trim(text)',
    'replace(text, find, with)',
    'replaceAll(text, find, with)',
    'repeat(text, times)',
    'format(value)',
    'split(text, separator)',
    'join(list, separator)',
    'link(label, url)',
  ],
  Math: [
    'add(a, b)',
    'subtract(a, b)',
    'multiply(a, b)',
    'divide(a, b)',
    'mod(a, b)',
    'pow(base, exponent)',
    'abs(number)',
    'round(number, places?)',
    'ceil(number)',
    'floor(number)',
    'sqrt(number)',
    'min(number, …)',
    'max(number, …)',
    'sum(number, …)',
    'mean(number, …)',
    'median(number, …)',
    'sign(number)',
    'toNumber(value)',
    'pi()',
    'e()',
  ],
  Date: [
    'now()',
    'today()',
    'dateAdd(date, amount, "days")',
    'dateSubtract(date, amount, "days")',
    'dateBetween(a, b, "days")',
    'dateStart(date)',
    'dateEnd(date)',
    'dateRange(start, end)',
    'formatDate(date, "YYYY-MM-DD")',
    'parseDate(text)',
    'year(date)',
    'month(date)',
    'date(date)',
    'day(date)',
    'hour(date)',
    'minute(date)',
    'week(date)',
    'timestamp(date)',
    'fromTimestamp(milliseconds)',
  ],
  People: ['name(person)', 'email(person)'],
  List: [
    'at(list, index)',
    'first(list)',
    'last(list)',
    'slice(list, start, end?)',
    'concat(list, …)',
    'sort(list)',
    'reverse(list)',
    'unique(list)',
    'includes(list, value)',
    'find(list, current > 1)',
    'findIndex(list, current > 1)',
    'filter(list, current > 1)',
    'some(list, current > 1)',
    'every(list, current > 1)',
    'map(list, current * 2)',
    'flat(list)',
  ],
  Other: ['prop("Name")', 'id()'],
}

export const FORMULA_FUNCTIONS: FormulaFunction[] = Object.entries(GROUPS).flatMap(([group, signatures]) =>
  signatures.map((signature) => ({ name: signature.slice(0, signature.indexOf('(')), signature, group })),
)
